CREATE TABLE match_team_members
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    match_team_id    BIGINT                                  NOT NULL,
    group_members_id BIGINT                                  NOT NULL,
    created_by       BIGINT,
    updated_by       BIGINT,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    CONSTRAINT pk_match_team_members PRIMARY KEY (id),
    CONSTRAINT fk_match_team_members_created_by
        FOREIGN KEY (created_by)
            REFERENCES users (id),
    CONSTRAINT fk_match_team_members_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES users (id),

    UNIQUE (
            match_team_id,
            group_members_id
        ),

    CONSTRAINT FK_MATCH_TEAM_MEMBERS_ON_GROUP_MEMBERS FOREIGN KEY (group_members_id) REFERENCES group_members (id),
    CONSTRAINT FK_MATCH_TEAM_MEMBERS_ON_MATCH_TEAM FOREIGN KEY (match_team_id) REFERENCES match_teams (id)
);

