CREATE TABLE match_sets
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    match_id             BIGINT                                  NOT NULL,
    set_number           INTEGER                                 NOT NULL,
    home_score           INTEGER                                 NOT NULL,
    away_score           INTEGER                                 NOT NULL,
    winner_match_team_id BIGINT,
    status               VARCHAR(255)                            NOT NULL,
    started_at           TIMESTAMP(6) WITHOUT TIME ZONE,
    finished_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    created_by           BIGINT,
    updated_by           BIGINT,
    created_at           TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at           TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    CONSTRAINT pk_match_sets PRIMARY KEY (id),
    CONSTRAINT FK_MATCH_SETS_ON_MATCH FOREIGN KEY (match_id) REFERENCES matches (id),
    CONSTRAINT FK_MATCH_SETS_ON_WINNER_MATCH_TEAM FOREIGN KEY (winner_match_team_id) REFERENCES match_teams (id),
    CHECK (
        status IN (
                   'SCHEDULED',
                   'IN_PROGRESS',
                   'FINISHED'
            )
        ),
    CHECK (
        home_score >= 0
        ),

    CHECK (
        away_score >= 0
        ),

    UNIQUE (
            match_id,
            set_number
        )
);

