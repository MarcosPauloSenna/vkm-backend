CREATE TABLE matches
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    game_day_id          BIGINT,
    tournament_id        BIGINT,
    tournament_stage_id  BIGINT,
    group_id             BIGINT,
    game_session_id      BIGINT,
    match_number         INTEGER,
    sequence_number      INTEGER,
    status               VARCHAR(255)                            NOT NULL DEFAULT 'SCHEDULED',
    winner_match_team_id BIGINT,
    started_at           TIMESTAMP(6) WITHOUT TIME ZONE,
    finished_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    created_by           BIGINT,
    updated_by           BIGINT,
    created_at           TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at           TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    CONSTRAINT pk_matches PRIMARY KEY (id),

    CONSTRAINT FK_MATCHES_ON_GAME_DAY FOREIGN KEY (game_day_id) REFERENCES game_days (id),

    CONSTRAINT FK_MATCHES_ON_GAME_SESSION FOREIGN KEY (game_session_id) REFERENCES game_sessions (id),

    CONSTRAINT FK_MATCHES_ON_GROUP FOREIGN KEY (group_id) REFERENCES groups (id),

    CONSTRAINT FK_MATCHES_ON_TOURNAMENT FOREIGN KEY (tournament_id) REFERENCES tournaments (id),

    CONSTRAINT FK_MATCHES_ON_TOURNAMENT_STAGE FOREIGN KEY (tournament_stage_id) REFERENCES tournament_stages (id),

    CONSTRAINT chk_match_sequence_number
        CHECK (
            sequence_number IS NULL OR sequence_number > 0
            ),
    CHECK (
        status IN (
                   'SCHEDULED',
                   'IN_PROGRESS',
                   'FINISHED',
                   'CANCELLED'
            )
        ),

    CONSTRAINT fk_matches_created_by
        FOREIGN KEY (created_by)
            REFERENCES users(id),

    CONSTRAINT fk_matches_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES users(id)
);

CREATE UNIQUE INDEX uq_match_session_sequence
    ON matches(game_session_id, sequence_number)
    WHERE game_session_id IS NOT NULL
        AND sequence_number IS NOT NULL;

