CREATE TABLE game_days
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    group_id      BIGINT      NOT NULL,
    tournament_id BIGINT,
    game_date     DATE        NOT NULL,
    location      VARCHAR(255) ,
    status        VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
        CHECK (status IN (
                          'SCHEDULED',
                          'OPEN',
                          'FINISHED',
                          'CANCELLED'
            )),
    notes         VARCHAR(255) ,
    created_by  BIGINT                                  NOT NULL,
    updated_by  BIGINT,
    created_at  TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at  TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,

    CONSTRAINT pk_game_days PRIMARY KEY (id),
    CONSTRAINT fk_game_days_group
        FOREIGN KEY (group_id)
            REFERENCES groups (id),

    CONSTRAINT fk_game_days_tournament
        FOREIGN KEY (tournament_id)
            REFERENCES tournaments (id),

    CONSTRAINT fk_game_days_created_by
        FOREIGN KEY (created_by)
            REFERENCES users(id),

    CONSTRAINT fk_game_days_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES users(id),

    CONSTRAINT uq_game_days_group_date
        UNIQUE (group_id, game_date)
);
