CREATE TABLE game_sessions
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    group_id      BIGINT                                  NOT NULL,
    tournament_id BIGINT                                  NOT NULL,
    game_day_id   BIGINT                                  NOT NULL,
    name          VARCHAR(255)                            NOT NULL,
    session_type  VARCHAR(255)                            NOT NULL,
    status        VARCHAR(255)                            NOT NULL,
    start_time    time(6) WITHOUT TIME ZONE,
    end_time      time(6) WITHOUT TIME ZONE,
    winner_stays  BOOLEAN                                 NOT NULL,
    loser_leaves  BOOLEAN                                 NOT NULL,
    max_points    INTEGER,
    created_by    BIGINT,
    updated_by    BIGINT,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    CONSTRAINT pk_game_sessions PRIMARY KEY (id),
    CONSTRAINT FK_GAME_SESSIONS_ON_GAME_DAY FOREIGN KEY (game_day_id) REFERENCES game_days (id),
    CONSTRAINT FK_GAME_SESSIONS_ON_GROUP FOREIGN KEY (group_id) REFERENCES groups (id),
    CONSTRAINT FK_GAME_SESSIONS_ON_TOURNAMENT FOREIGN KEY (tournament_id) REFERENCES tournaments (id),

    CONSTRAINT fk_game_sessions_created_by
        FOREIGN KEY (created_by)
            REFERENCES users (id),

    CONSTRAINT fk_game_sessions_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES users (id),

    CONSTRAINT chk_game_session_type
        CHECK (
            session_type IN (
                             'CASUAL',
                             'KING_OF_COURT',
                             'TOURNAMENT',
                             'ROTATION',
                             'FREE'
                )
            ),

    CONSTRAINT chk_game_session_status
        CHECK (
            status IN (
                       'OPEN',
                       'PAUSED',
                       'FINISHED',
                       'CANCELLED'
                )
            ),

    CONSTRAINT chk_game_session_max_points
        CHECK (
            max_points IS NULL OR max_points > 0
            ),

    CONSTRAINT chk_game_session_time
        CHECK (
            start_time IS NULL
                OR end_time IS NULL
                OR end_time >= start_time
            ),
    CONSTRAINT uq_game_sessions_id_day
        UNIQUE (id, game_day_id)
);



