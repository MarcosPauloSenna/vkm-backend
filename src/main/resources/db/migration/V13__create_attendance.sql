CREATE TABLE attendance
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_by      BIGINT,
    updated_by      BIGINT,
    created_at      TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at      TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    game_day_id     BIGINT                                  NOT NULL,
    group_member_id BIGINT                                  NOT NULL,
    status          VARCHAR(255)                            NOT NULL,
    check_in_at     TIMESTAMP(6) WITHOUT TIME ZONE,
    notes           VARCHAR(255),
    CONSTRAINT pk_attendance PRIMARY KEY (id),

    CONSTRAINT FK_ATTENDANCE_ON_GAME_DAY FOREIGN KEY (game_day_id) REFERENCES game_days (id),
    CONSTRAINT FK_ATTENDANCE_ON_GROUP_MEMBER FOREIGN KEY (group_member_id) REFERENCES group_members (id),
    CONSTRAINT uq_attendance_id_day
        UNIQUE (id, game_day_id),
    UNIQUE (
            game_day_id,
            group_member_id
        ),
    CHECK (
        status IN (
                   'PRESENT',
                   'ABSENT',
                   'EXCUSED'
            )
        )
);

