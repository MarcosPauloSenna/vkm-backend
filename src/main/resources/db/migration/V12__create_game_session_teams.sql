CREATE TABLE game_session_teams
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    game_session_id BIGINT                                  NOT NULL,
    team_id         BIGINT                                  NOT NULL,
    queue_position  INTEGER,
    status          VARCHAR(255)                            NOT NULL DEFAULT 'WAITING',
    joined_at       TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    created_by      BIGINT,
    updated_by      BIGINT,
    created_at      TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at      TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    CONSTRAINT pk_game_session_teams PRIMARY KEY (id),

    CONSTRAINT fk_gst_game_session
        FOREIGN KEY (game_session_id)
            REFERENCES game_sessions(id),

    CONSTRAINT fk_gst_team
        FOREIGN KEY (team_id)
            REFERENCES teams(id),

    CONSTRAINT uq_gst_session_team
        UNIQUE (game_session_id, team_id),

    CONSTRAINT chk_gst_queue_position
        CHECK (queue_position IS NULL OR queue_position > 0),

    CONSTRAINT fk_gst_created_by
        FOREIGN KEY (created_by)
            REFERENCES users(id),

    CONSTRAINT fk_gst_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES users(id),

    CHECK (
        status IN (
                   'WAITING',
                   'PLAYING',
                   'FINISHED',
                   'INACTIVE'
            )
        )

);

CREATE INDEX idx_gst_session_status_position
    ON game_session_teams (
                           game_session_id,
                           status,
                           queue_position
        );

