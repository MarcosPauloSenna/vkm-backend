CREATE TABLE game_session_members
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    game_day_id     BIGINT                                  NOT NULL,
    game_session_id BIGINT                                  NOT NULL,
    attendance_id   BIGINT                                  NOT NULL,
    status          VARCHAR(255)                            NOT NULL DEFAULT 'PARTICIPATING',
    joined_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    left_at         TIMESTAMP(6) WITHOUT TIME ZONE,
    created_by      BIGINT,
    updated_by      BIGINT,
    created_at      TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at      TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,

    CONSTRAINT pk_game_session_members PRIMARY KEY (id),

    CONSTRAINT fk_gsm_session_day
        FOREIGN KEY (game_session_id, game_day_id)
            REFERENCES game_sessions (id, game_day_id),

    CONSTRAINT fk_gsm_attendance_day
        FOREIGN KEY (attendance_id, game_day_id)
            REFERENCES attendance (id, game_day_id),

    CONSTRAINT uq_gsm_session_attendance
        UNIQUE (game_session_id, attendance_id),

    CONSTRAINT fk_gsm_created_by
        FOREIGN KEY (created_by)
            REFERENCES users(id),

    CONSTRAINT fk_gsm_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES users(id),

    CHECK (status IN (
                      'PARTICIPATING',
                      'LEFT',
                      'WITHDRAWN'
        ))
);
