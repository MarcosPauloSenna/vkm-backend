CREATE TABLE match_teams
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    match_id           BIGINT                                  NOT NULL,
    team_id            BIGINT,
    tournament_team_id BIGINT,
    position           INTEGER                                 NOT NULL,
    name               VARCHAR(255)                            NOT NULL,
    side               VARCHAR(255)                            NOT NULL,
    created_by         BIGINT,
    updated_by         BIGINT,
    created_at         TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    updated_at         TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    CONSTRAINT pk_match_teams PRIMARY KEY (id),

    CONSTRAINT FK_MATCH_TEAMS_ON_MATCH FOREIGN KEY (match_id) REFERENCES matches (id),

    CONSTRAINT FK_MATCH_TEAMS_ON_TEAM FOREIGN KEY (team_id) REFERENCES teams (id),
    CONSTRAINT FK_MATCH_TEAMS_ON_TOURNAMENT_TEAM FOREIGN KEY (tournament_team_id) REFERENCES tournaments_teams (id),
    CONSTRAINT fk_match_teams_created_by
        FOREIGN KEY (created_by)
            REFERENCES users(id),
    CONSTRAINT fk_match_teams_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES users(id),

    UNIQUE (
            match_id,
            side
        ),

        CONSTRAINT chk_match_team_position
        CHECK (position > 0)
);

ALTER TABLE matches
    ADD CONSTRAINT FK_MATCHES_ON_WINNER_MATCH_TEAM FOREIGN KEY (winner_match_team_id) REFERENCES match_teams (id);

CREATE UNIQUE INDEX uq_match_team_position
    ON match_teams(match_id, position);

CREATE UNIQUE INDEX uq_match_team
    ON match_teams(match_id, team_id);